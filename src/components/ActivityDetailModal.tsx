import React, { useState } from 'react';
import { X, Copy, Check, Volume2, VolumeX, Sparkles, Clock, Share2, Trash2 } from 'lucide-react';
import { sound } from '../utils/audio';
import { ActivityItem } from '../types';
import {
  VoiceProfileId,
  VOICE_PROFILES,
  speakWithProfile,
  stopSpeech,
  getStoredVoiceProfileId,
} from '../utils/speech';

interface ActivityDetailModalProps {
  activity: ActivityItem | null;
  onClose: () => void;
  onDelete: (id: string) => void;
  onRerun: (activity: ActivityItem) => void;
  voiceProfile?: VoiceProfileId;
}

export const ActivityDetailModal: React.FC<ActivityDetailModalProps> = ({
  activity,
  onClose,
  onDelete,
  onRerun,
  voiceProfile = getStoredVoiceProfileId(),
}) => {
  if (!activity) return null;

  const [copied, setCopied] = useState(false);
  const [isSpeaking, setIsSpeaking] = useState(false);

  const handleCopy = () => {
    navigator.clipboard.writeText(activity.outputSnippet);
    setCopied(true);
    sound.playChirp();
    setTimeout(() => setCopied(false), 2000);
  };

  const handleSpeak = () => {
    if (typeof window === 'undefined') return;
    if (isSpeaking) {
      stopSpeech();
      setIsSpeaking(false);
      return;
    }
    sound.playChirp();
    speakWithProfile(
      activity.outputSnippet,
      voiceProfile,
      () => setIsSpeaking(true),
      () => setIsSpeaking(false)
    );
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fadeIn">
      <div className="relative w-full max-w-md rounded-3xl bg-[#070e24] border border-cyan-500/30 p-5 flex flex-col max-h-[90vh] overflow-y-auto text-slate-100 shadow-[0_0_50px_rgba(6,182,212,0.3)]">
        {/* Header */}
        <div className="flex items-center justify-between pb-3 border-b border-cyan-500/20">
          <div>
            <div className="flex items-center gap-2">
              <h3 className="text-sm font-bold text-white tracking-wide">
                {activity.actionTitle}
              </h3>
              <span className="px-2 py-0.5 rounded-full text-[10px] font-semibold bg-cyan-500/20 text-cyan-300 border border-cyan-500/30">
                {activity.appName}
              </span>
            </div>
            <div className="flex items-center gap-1 text-[11px] text-slate-400 mt-0.5">
              <Clock className="w-3 h-3" />
              <span>{activity.timestamp}</span>
            </div>
          </div>

          <button
            onClick={onClose}
            className="w-7 h-7 rounded-full bg-slate-800 flex items-center justify-center text-slate-300 hover:text-white transition-colors cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Original Prompt */}
        <div className="mt-4">
          <label className="text-xs font-semibold text-slate-400 uppercase tracking-wider block mb-1">
            Prompt / Input Context:
          </label>
          <div className="p-3 rounded-2xl bg-slate-900 border border-slate-800 text-xs text-slate-300 italic">
            "{activity.promptSnippet || 'Automated smart action generated by Riyaz AI.'}"
          </div>
        </div>

        {/* Generated Text */}
        <div className="mt-4">
          <div className="flex items-center justify-between mb-1.5">
            <label className="text-xs font-semibold text-cyan-300 flex items-center gap-1.5">
              <Sparkles className="w-3.5 h-3.5" />
              Riyaz AI Output:
            </label>
            <div className="flex items-center gap-1.5">
              <button
                onClick={handleSpeak}
                className={`p-1.5 rounded-lg transition-colors cursor-pointer flex items-center gap-1 ${
                  isSpeaking
                    ? 'bg-red-500/20 text-red-300 border border-red-500/40 shadow-[0_0_10px_rgba(239,68,68,0.3)]'
                    : 'bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-cyan-300'
                }`}
                title={isSpeaking ? 'Stop speaking' : `Read aloud with ${VOICE_PROFILES[voiceProfile]?.name || 'active'} voice`}
              >
                {isSpeaking ? (
                  <>
                    <VolumeX className="w-3.5 h-3.5 text-red-400" />
                    <span className="text-[10px] font-semibold text-red-300">Stop</span>
                  </>
                ) : (
                  <Volume2 className="w-3.5 h-3.5" />
                )}
              </button>
              <button
                onClick={handleCopy}
                className="flex items-center gap-1 px-2.5 py-1 rounded-lg bg-cyan-500/20 border border-cyan-400/40 text-cyan-200 hover:bg-cyan-500/30 text-[11px] font-semibold transition-colors"
              >
                {copied ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-400" />
                    <span>Copied</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5" />
                    <span>Copy</span>
                  </>
                )}
              </button>
            </div>
          </div>

          <div className="p-3.5 rounded-2xl bg-slate-900/90 border border-cyan-500/30 text-xs text-slate-100 whitespace-pre-wrap leading-relaxed max-h-52 overflow-y-auto">
            {activity.outputSnippet}
          </div>
        </div>

        {/* Footer actions */}
        <div className="mt-5 pt-3 border-t border-slate-800 flex items-center justify-between">
          <button
            onClick={() => {
              onDelete(activity.id);
              onClose();
            }}
            className="flex items-center gap-1 text-xs text-rose-400 hover:text-rose-300 transition-colors cursor-pointer"
          >
            <Trash2 className="w-3.5 h-3.5" />
            <span>Remove</span>
          </button>

          <button
            onClick={() => {
              onRerun(activity);
              onClose();
            }}
            className="px-3.5 py-1.5 rounded-xl bg-gradient-to-r from-cyan-500 to-blue-600 text-xs font-bold text-white shadow-md cursor-pointer flex items-center gap-1.5"
          >
            <Sparkles className="w-3.5 h-3.5" />
            <span>Re-open in Studio</span>
          </button>
        </div>
      </div>
    </div>
  );
};
